"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { Check, FlaskConical, Loader2 } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Input } from "@/components/ui/input";
import type { LabResult } from "@/lib/studio/lab";

type Version = { version: number; status: string; source: string; spec: Record<string, unknown>; specHash: string; lock: unknown };
type Auth = { tool: string; title: string; risk: string; permission: string; declared: string; effective: string; needsApprovalAnyway: boolean }[];
type Review = { reviewer: string; decision: string; note: string; created_at: string };

const RISK_STYLE: Record<string, string> = { read: "text-muted-foreground", write: "text-amber-700 dark:text-amber-300", high_impact: "font-medium text-destructive" };

/** One Worker: edit its spec, see what it may do, test it as personas, send it for human review, publish it. */
export function WorkerEditor({ workerId, versions, authority, problems, reviews, personas }: {
  workerId: string; versions: Version[]; authority: Auth | null; problems: string[]; reviews: Review[]; personas: { key: string; label: string; role: string }[];
}) {
  const router = useRouter();
  const latest = versions[0]!;
  const frozen = latest.status === "published" || latest.status === "retired";
  const [json, setJson] = useState(JSON.stringify(latest.spec, null, 2));
  const [busy, setBusy] = useState<string | null>(null);
  const [msg, setMsg] = useState<{ ok: boolean; text: string; problems?: string[] } | null>(null);
  const [checks, setChecks] = useState({ instructions_read: false, tools_reviewed: false, authority_reviewed: false });
  const [note, setNote] = useState("");

  const [persona, setPersona] = useState(personas[0]!.key);
  const [prompt, setPrompt] = useState("I need a room for 6 people tomorrow from 2pm to 3pm for a study group.");
  const [lab, setLab] = useState<LabResult | null>(null);
  const [labErr, setLabErr] = useState("");

  async function call(kind: string, path: string, method: string, body?: unknown, ok?: string) {
    setBusy(kind); setMsg(null);
    const res = await fetch(path, { method, headers: { "Content-Type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body) }).catch(() => null);
    const d = res ? await res.json().catch(() => ({})) : {};
    setBusy(null);
    if (!res || !res.ok) { setMsg({ ok: false, text: d.error ?? "That did not work.", problems: d.problems }); return null; }
    setMsg({ ok: true, text: ok ?? "Done." });
    router.refresh();
    return d;
  }

  async function save() {
    let spec: unknown;
    try { spec = JSON.parse(json); } catch { setMsg({ ok: false, text: "That is not valid JSON." }); return; }
    await call("save", `/api/platform/workers/${workerId}`, "PUT", { spec }, frozen ? "Started a new version." : "Draft saved.");
  }

  async function runLab() {
    setBusy("lab"); setLabErr(""); setLab(null);
    const res = await fetch("/api/platform/lab/run", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ workerId, persona, prompt }) }).catch(() => null);
    const d = res ? await res.json().catch(() => ({})) : {};
    setBusy(null);
    if (!res || !res.ok) { setLabErr([d.error, ...(d.problems ?? [])].filter(Boolean).join(" · ") || "The test run failed."); return; }
    setLab(d);
  }
  async function decide(approvalId: string, decision: "approve" | "decline") {
    const res = await fetch("/api/platform/lab/decide", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ approvalId, persona: "admin", decision, reason: "Decided in the Test Lab" }) });
    const d = await res.json().catch(() => ({}));
    setLabErr(res.ok ? "" : d.error ?? "Could not decide.");
    if (res.ok && lab) setLab({ ...lab, trace: { ...lab.trace, approvals: lab.trace.approvals.map((a) => (a.id === approvalId ? { ...a, status: decision === "approve" ? "approved" : "declined" } : a)) } });
  }

  const v = latest.version;
  const base = `/api/platform/workers/${workerId}/versions/${v}`;
  return (
    <div className="space-y-8">
      <div>
        <h1 className="text-xl font-semibold">{String(latest.spec.name)}</h1>
        <p className="text-sm text-muted-foreground"><span className="font-mono">{workerId}</span> · version {v} · {latest.status.replace("_", " ")}{latest.source === "generated" ? " · generated by the builder" : ""}</p>
      </div>
      {msg && <div role="status" className={msg.ok ? "text-sm text-emerald-700 dark:text-emerald-300" : "text-sm text-destructive"}>{msg.text}{msg.problems?.map((p) => <div key={p}>· {p}</div>)}</div>}

      <section className="space-y-3 rounded-2xl border bg-card p-5">
        <div className="font-medium">Spec</div>
        <Textarea className="h-80 font-mono text-xs" value={json} onChange={(e) => setJson(e.target.value)} spellCheck={false} />
        <div className="flex gap-2">
          <Button disabled={busy !== null} onClick={save}>{busy === "save" && <Loader2 className="animate-spin" />} {frozen ? "Save as a new version" : "Save draft"}</Button>
        </div>
      </section>

      <section className="space-y-3 rounded-2xl border bg-card p-5">
        <div className="font-medium">What it may do</div>
        {problems.length > 0 && <div role="alert" className="text-sm text-destructive">{problems.map((p) => <div key={p}>· {p}</div>)}</div>}
        {authority && (
          <table className="w-full text-sm">
            <thead className="text-left text-xs text-muted-foreground"><tr><th className="py-1">Tool</th><th>Risk</th><th>Permission needed</th><th>Policy</th></tr></thead>
            <tbody>
              {authority.map((a) => (
                <tr key={a.tool} className="border-t">
                  <td className="py-1.5">{a.title}<div className="font-mono text-xs text-muted-foreground">{a.tool}</div></td>
                  <td className={RISK_STYLE[a.risk]}>{a.risk.replace("_", " ")}</td>
                  <td className="font-mono text-xs">{a.permission}</td>
                  <td>{a.effective}{a.declared !== a.effective ? ` (was ${a.declared})` : ""}{a.needsApprovalAnyway ? " · always needs another person" : ""}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
        <p className="text-xs text-muted-foreground">At run time this is intersected with the person&apos;s own permissions and the organisation&apos;s policy. A Worker can never do more than the person using it.</p>
      </section>

      <section className="space-y-3 rounded-2xl border bg-card p-5">
        <div className="flex items-center gap-2 font-medium"><FlaskConical className="size-4" /> Test Lab</div>
        <p className="text-sm text-muted-foreground">Runs this draft on the platform test stack (invented university, synthetic data) as a persona with that persona&apos;s real permissions.</p>
        <div className="flex flex-wrap gap-2">
          {personas.map((p) => (
            <button key={p.key} type="button" onClick={() => setPersona(p.key)} aria-pressed={persona === p.key}
              className={`rounded-full border px-3 py-1 text-sm ${persona === p.key ? "border-primary bg-primary text-primary-foreground" : "bg-background hover:bg-muted"}`}>{p.label}</button>
          ))}
        </div>
        <Textarea rows={2} value={prompt} onChange={(e) => setPrompt(e.target.value)} />
        <Button disabled={busy !== null} onClick={runLab}>{busy === "lab" && <Loader2 className="animate-spin" />} Run as {personas.find((p) => p.key === persona)?.label}</Button>
        {labErr && <p role="alert" className="text-sm text-destructive">{labErr}</p>}
        {lab && (
          <div className="space-y-3 rounded-lg border bg-muted/30 p-4 text-sm">
            <div><div className="text-xs font-medium uppercase tracking-wide text-muted-foreground">Answer</div><p className="whitespace-pre-wrap">{lab.answer || "(no text)"}</p></div>
            <div>
              <div className="text-xs font-medium uppercase tracking-wide text-muted-foreground">Trace · {lab.trace.status}{lab.trace.durationMs ? ` · ${(lab.trace.durationMs / 1000).toFixed(1)}s` : ""}</div>
              <div className="text-xs text-muted-foreground">Tools offered to {lab.persona.label}: {lab.trace.toolsOffered.join(", ") || "none"}</div>
              <ul className="mt-1 space-y-1">
                {lab.trace.toolCalls.map((c, i) => <li key={i} className="font-mono text-xs"><b>{c.tool}</b> → {c.decision.toUpperCase()} · {c.status}{c.reason ? ` (${c.reason})` : ""}</li>)}
                {lab.trace.toolCalls.length === 0 && <li className="text-xs text-muted-foreground">No tool was called.</li>}
              </ul>
              {lab.trace.prepared.map((p) => <div key={p.id} className="mt-1 text-xs">Prepared for the person to confirm: {p.summary} ({p.status})</div>)}
              {lab.trace.approvals.map((a) => (
                <div key={a.id} className="mt-1 flex flex-wrap items-center gap-2 text-xs">
                  <span>Waiting for another person to approve: {a.summary} ({a.status})</span>
                  {a.status === "pending" && (<><Button size="sm" onClick={() => decide(a.id, "approve")}>Approve as Department Admin</Button><Button size="sm" variant="outline" onClick={() => decide(a.id, "decline")}>Decline</Button></>)}
                </div>
              ))}
            </div>
          </div>
        )}
      </section>

      <section className="space-y-3 rounded-2xl border bg-card p-5">
        <div className="font-medium">Review and publish</div>
        {reviews.map((r, i) => <div key={i} className="text-sm text-muted-foreground">{r.decision === "approve" ? "Approved" : "Rejected"} by {r.reviewer}{r.note ? `: ${r.note}` : ""}</div>)}
        {latest.status === "draft" && <Button disabled={busy !== null} onClick={() => call("req", `${base}/request-review`, "POST", undefined, "Sent to review.")}>Send to review</Button>}
        {latest.status === "in_review" && (
          <div className="space-y-2 text-sm">
            <p>A person must read this Worker before it can be published. Tick what you have actually checked.</p>
            {([["instructions_read", "I read the instructions"], ["tools_reviewed", "I reviewed the tools it can use"], ["authority_reviewed", "I reviewed what needs a confirmation or another person's approval"]] as const).map(([k, label]) => (
              <label key={k} className="flex items-center gap-2"><input type="checkbox" checked={checks[k]} onChange={(e) => setChecks({ ...checks, [k]: e.target.checked })} /> {label}</label>
            ))}
            <Input placeholder="Note (optional)" value={note} onChange={(e) => setNote(e.target.value)} />
            <div className="flex gap-2">
              <Button disabled={busy !== null || !Object.values(checks).every(Boolean)} onClick={() => call("appr", `${base}/review`, "POST", { decision: "approve", specHash: latest.specHash, checklist: checks, note }, "Approved.")}><Check /> Approve</Button>
              <Button variant="outline" disabled={busy !== null} onClick={() => call("rej", `${base}/review`, "POST", { decision: "reject", specHash: latest.specHash, checklist: checks, note }, "Sent back to draft.")}>Send back</Button>
            </div>
          </div>
        )}
        {latest.status === "approved" && <Button disabled={busy !== null} onClick={() => call("pub", `${base}/publish`, "POST", undefined, "Published. It is now frozen.")}>Publish version {v}</Button>}
        {latest.status === "published" && <p className="text-sm text-emerald-700 dark:text-emerald-300">Published and frozen. Include it in a release on the Releases page. Saving a change starts a new version.</p>}
      </section>

      <section className="rounded-2xl border bg-card">
        <div className="border-b px-5 py-3.5 text-sm font-semibold">Versions</div>
        <ul className="divide-y text-sm">{versions.map((x) => <li key={x.version} className="flex justify-between px-5 py-3"><span>Version {x.version}</span><span className="text-muted-foreground">{x.status.replace("_", " ")}</span></li>)}</ul>
      </section>
    </div>
  );
}
